# 10. MAIN UNIFIED AGENT
# ============================================================

def answer_question(
    question,
    user,
    history=None,
    last_query=None,
    client=None,
    model=None,
    dataset=None,
    document_id=None,
):
    """
    Main Pricing Copilot entry point.

    Supports:
    - SQL
    - Documents
    - Combined analysis
    - Financial period analytics
    - Charts
    - Financial PDF report actions
    """

    question = str(
        question or ""
    ).strip()

    if not question:
        raise AgentError(
            "Please enter a question."
        )

    if len(question) > MAX_QUESTION_CHARACTERS:
        raise AgentError(
            "Questions must contain no more "
            "than 4,000 characters."
        )

    history = _safe_history(history)

    original_question = question

    # --------------------------------------------------
    # STEP 1: CLASSIFY QUESTION
    # --------------------------------------------------

    classification = classify_scope(
        question,
        history=history,
        client=client,
        model=model,
    )

    route = classification["route"]

    # --------------------------------------------------
    # STEP 2: OUT-OF-SCOPE
    # --------------------------------------------------

    if route == "out_of_scope":
        return _out_of_scope_response(
            original_question
        )

    # --------------------------------------------------
    # STEP 3: REPORT GENERATION REQUEST
    # --------------------------------------------------

    if detect_report_request(question):
        if route in {"sql", "followup"}:
            selected_dataset = (
                detect_explicit_dataset(question)
                or dataset
            )

            if not selected_dataset and last_query:
                selected_dataset = last_query.get(
                    "dataset"
                )

            return _report_response(
                original_question,
                user,
                dataset=selected_dataset,
            )

    # --------------------------------------------------
    # STEP 4: RESOLVE FOLLOW-UP
    # --------------------------------------------------

    if route == "followup":
        resolved = _resolve_followup(
            question,
            history,
        )

        if resolved != question:
            question = resolved

            route = classify_scope(
                question,
                history=history,
                client=client,
                model=model,
            )["route"]

        elif last_query:
            route = "sql"

        elif document_id:
            route = "documents"

        else:
            return _empty_response(
                original_question,
                "Please specify which previous "
                "financial result or document "
                "you want to continue analyzing.",
                route="clarify",
            )

    # --------------------------------------------------
    # STEP 5: AMBIGUOUS QUESTIONS
    # --------------------------------------------------

    if route == "clarify":
        return _empty_response(
            original_question,
            "I can help with financial SQL analysis, "
            "finance-related documents, financial "
            "visualizations and PDF reports. "
            "Please clarify what you want to analyze.",
            route="clarify",
        )

    if route == "out_of_scope":
        return _out_of_scope_response(
            original_question
        )

    if route not in {
        "sql",
        "documents",
        "both",
    }:
        return _empty_response(
            original_question,
            "Please clarify your financial question.",
            route="clarify",
        )

    # --------------------------------------------------
    # STEP 6: COMBINED ANALYSIS
    # --------------------------------------------------

    if route == "both":
        return _combined_response(
            original_question,
            user,
            history=history,
            last_query=last_query,
            document_id=document_id,
            client=client,
            model=model,
        )

    # --------------------------------------------------
    # STEP 7: DOCUMENT ANALYSIS
    # --------------------------------------------------

    if route == "documents":
        return _document_response(
            original_question,
            user,
            history=history,
            document_id=document_id,
            client=client,
            model=model,
        )

    # --------------------------------------------------
    # STEP 8: SQL ANALYSIS
    # --------------------------------------------------

    explicit_dataset = detect_explicit_dataset(
        question
    )

    selected_dataset = (
        explicit_dataset or dataset
    )

    if not selected_dataset and last_query:
        selected_dataset = last_query.get(
            "dataset"
        )

    procurement_advice = bool(
        re.search(
            r"\b(procurement|purchasing|"
            r"purchase orders?)\b",
            question,
            re.I,
        )
        and re.search(
            r"\b(reduce|improve|optimize|optimise|"
            r"overspending|recommend|"
            r"cost control|how can)\b",
            question,
            re.I,
        )
    )

    if procurement_advice:
        return _procurement_advice(
            original_question,
            user,
        )

    previous_query = last_query

    if (
        explicit_dataset
        and last_query
        and last_query.get("dataset")
        != explicit_dataset
    ):
        previous_query = None

    return _sql_response(
        original_question,
        user,
        last_query=previous_query,
        dataset=selected_dataset,
    )


