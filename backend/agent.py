    response["answer"] = (
        "### Procurement spending analysis\n\n"
        + str(result.get("message") or "")
        + "\n\n"
        + "The budget comparison describes "
        + "recorded procurement performance. "
        + "To investigate overspending, review "
        + "supplier costs, departmental variances "
        + "and high-value purchase orders. "
        + "Aggregate results alone do not "
        + "establish the underlying causes."
    )

    response["recommendations"] = [
        "Investigate the largest supplier and "
        "departmental spending variances.",

        "Review high-value purchase orders "
        "against applicable approval policies.",

        "Compare spending across periods to "
        "identify recurring increases.",
    ]

    response["suggestions"] = [
        "Break down procurement spending by Supplier",
        "Show procurement budget variances",
        "Show the top 5 procurement orders",
    ]

    return _normalize_response(response)


