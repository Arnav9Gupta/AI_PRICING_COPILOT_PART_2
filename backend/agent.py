def _sql_response(
    question,
    user,
    last_query=None,
    dataset=None,
    operation=None,
):
    if user.get("role") != "Admin":
        raise PermissionError(
            "SQL datasets are restricted "
            "to administrators."
        )

    if dataset:
        if dataset not in de.allowed_datasets(user):
            raise PermissionError(
                "You are not authorized to access "
                "the selected SQL dataset."
            )

    # Resolve financial period questions.
    period_spec = fl.resolve_financial_period(
        question
    )

    if period_spec:
        selected = (
            dataset
            or detect_explicit_dataset(question)
        )

        if not selected and last_query:
            selected = last_query.get("dataset")

        if not selected:
            return _empty_response(
                question,
                "Please specify which financial "
                "dataset you want to analyze.",
                route="clarify",
            )

        if selected not in de.allowed_datasets(user):
            raise PermissionError(
                "Dataset access denied."
            )

        followup = bool(
            re.search(
                r"\b(same|those|that|again|"
                r"now|and for)\b",
                question,
                re.I,
            )
        )

        inherited = {}

        if (
            followup
            and last_query
            and last_query.get("dataset") == selected
        ):
            inherited = dict(
                last_query.get("filters") or {}
            )

            inherited.pop("start_date", None)
            inherited.pop("end_date", None)

        raw = {
            "dataset": selected,
            "filters": inherited,
            **period_spec,
            "period_type": (
                period_spec.get("comparison_type")
                or period_spec.get("period_type")
            ),
        }

        if (
            followup
            and last_query
            and last_query.get("dataset") == selected
        ):
            raw["measure"] = last_query.get(
                "measure"
            )

        query = chatbot.normalize_query(raw)

    else:
        query = chatbot.understand_question(
            question,
            last_query=last_query,
            dataset=dataset,
            user=user,
        )

    if dataset:
        query["dataset"] = dataset

    if operation:
        query["operation"] = operation

    selected = query.get("dataset")

    if selected not in de.allowed_datasets(user):
        raise PermissionError(
            "You are not authorized to access "
            "the requested SQL dataset."
        )

    result = chatbot.execute_query(
        query,
        user,
    )

    suggestions = []

    if not result.get("error"):
        try:
            suggestions = chatbot.suggest_followups(
                query,
                result,
                user,
            )
        except Exception:
            logger.exception(
                "Follow-up generation failed"
            )

    chart = _build_chart(
        query,
        result,
        user,
    )

    return _normalize_response({
        "question": question,
        "route": "sql",
        "query": query,
        "result": result,
        "answer": result.get("message", ""),
        "suggestions": suggestions,
        "recommendations": [],
        "insights": [],
        "visualization": chart,
    })


