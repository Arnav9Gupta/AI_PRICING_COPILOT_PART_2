def _build_chart(query, result, user):
    """
    Create a chart only from successful,
    authorized deterministic SQL results.
    """

    if result.get("error") or result.get("empty"):
        return None

    if user.get("role") != "Admin":
        return None

    dataset = query.get("dataset")

    if dataset not in de.allowed_datasets(user):
        return None

    if result.get("dataset") != dataset:
        return None

    if result.get("verification_method") != (
        "deterministic_sql_execution"
    ):
        return None

    if de.dataset_access_problem(user, dataset):
        return None

    try:
        return visualization.build_visualization(
            query=query,
            result=result,
            user=user,
        )

    except Exception:
        logger.exception(
            "Visualization generation failed"
        )
        return None


