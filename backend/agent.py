def _safe_history(history):
    safe = []

    for item in (history or [])[-10:]:
        if not isinstance(item, dict):
            continue

        role = item.get("role")
        content = str(
            item.get("content") or ""
        ).strip()

        if (
            role in {"user", "assistant"}
            and content
        ):
            safe.append({
                "role": role,
                "content": content[:1000],
            })

    return safe


def classify_scope(
    question,
    history=None,
    client=None,
    model=None,
):
    """
    Determine the correct route using GPT-OSS.

    Fails closed when classification is unavailable.
    """

    active_client = (
        client if client is not None
        else chatbot.client
    )

    active_model = model or chatbot.MODEL

    if active_client is None:
        return {
            "route": "clarify",
            "reason": "Scope classifier unavailable.",
        }

    payload = {
        "question": str(question)[:4000],
        "history": _safe_history(history)[-6:],
    }

    try:
        response = (
            active_client.chat.completions.create(
                model=active_model,
                temperature=0,
                response_format={
                    "type": "json_object"
                },
                messages=[
                    {
                        "role": "system",
                        "content": SCOPE_CLASSIFIER_PROMPT,
                    },
                    {
                        "role": "user",
                        "content": json.dumps(
                            payload,
                            ensure_ascii=False,
                        ),
                    },
                ],
            )
        )

        parsed = json.loads(
            response.choices[0].message.content
            or "{}"
        )

        route = parsed.get("route")

        if route not in {
            "sql",
            "documents",
            "both",
            "followup",
            "clarify",
            "out_of_scope",
        }:
            route = "clarify"

        return {
            "route": route,
            "reason": str(
                parsed.get("reason") or ""
            )[:300],
        }

    except Exception:
        logger.exception(
            "Scope classification failed"
        )

        return {
            "route": "clarify",
            "reason": "Unable to classify question.",
        }


def detect_tool_intent(question):
    """
    Compatibility helper for older API routes.

    This is not an authorization boundary.
    """

    return classify_scope(question)["route"]


