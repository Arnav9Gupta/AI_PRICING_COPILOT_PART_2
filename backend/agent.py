def detect_report_request(question):
    """
    Recognize explicit financial PDF report requests.

    Does not generate files or bypass authorization.
    """

    value = str(question or "").lower()

    has_report = bool(
        re.search(
            r"\b(report|pdf|export|download)\b",
            value,
        )
    )

    has_action = bool(
        re.search(
            r"\b(generate|create|prepare|build|"
            r"export|download|produce|make)\b",
            value,
        )
    )

    return has_report and has_action


def _report_filters(question):
    """
    Resolve a simple date expression.

    Avoid silently misinterpreting multi-date
    ranges. More complex filtering should be
    handled through a validated report form.
    """

    value = str(question or "")

    # Two explicit ISO dates.
    dates = re.findall(
        r"\b\d{4}-\d{2}-\d{2}\b",
        value,
    )

    if len(dates) >= 2:
        from datetime import date

        try:
            start = date.fromisoformat(dates[0])
            end = date.fromisoformat(dates[1])

            if start > end:
                raise ValueError(
                    "Start date is after end date."
                )

            return {
                "start_date": start.isoformat(),
                "end_date": end.isoformat(),
            }

        except ValueError as exc:
            raise AgentError(
                "Invalid report date range."
            ) from exc

    if len(dates) == 1:
        parsed = fl.parse_date_expression(value)
        return parsed or {}

    # Do not guess a range containing two
    # different month expressions.
    month_pattern = (
        r"\b(?:Jan(?:uary)?|Feb(?:ruary)?|"
        r"Mar(?:ch)?|Apr(?:il)?|May|Jun(?:e)?|"
        r"Jul(?:y)?|Aug(?:ust)?|Sep(?:tember)?|"
        r"Oct(?:ober)?|Nov(?:ember)?|"
        r"Dec(?:ember)?)\s+\d{4}\b"
    )

    if len(re.findall(
        month_pattern,
        value,
        re.I,
    )) > 1:
        raise AgentError(
            "Please specify the report date range "
            "using YYYY-MM-DD dates."
        )

    parsed = fl.parse_date_expression(value)

    return parsed or {}


def _report_response(
    question,
    user,
    dataset=None,
):
    """
    Prepare a PDF report action for the frontend.

    The actual PDF is generated separately by
    the protected FastAPI endpoint.
    """

    if user.get("role") != "Admin":
        raise PermissionError(
            "Only administrators can generate "
            "financial SQL reports."
        )

    selected = (
        detect_explicit_dataset(question)
        or dataset
    )

    if not selected:
        return _empty_response(
            question,
            "Please specify the financial dataset "
            "for your PDF report, such as HR Payroll, "
            "Sales Orders or Procurement Orders.",
            route="clarify",
        )

    if selected not in REPORT_DATASETS:
        return _empty_response(
            question,
            "This financial dataset is not supported "
            "for PDF report generation.",
            route="clarify",
        )

    if selected not in de.allowed_datasets(user):
        raise PermissionError(
            "You are not authorized to generate "
            "a report for this dataset."
        )

    problem = de.dataset_access_problem(
        user,
        selected,
    )

    if problem:
        raise PermissionError(problem)

    filters = _report_filters(question)

    # No PDF is generated at this stage.
    # The download endpoint validates all
    # filters and permissions again.
    action = {
        "type": "financial_pdf",
        "dataset": selected,
        "filters": filters,
        "endpoint": "/reports/generate",
        "method": "POST",
        "label": "Download Financial PDF",
    }

    return _normalize_response({
        "question": question,
        "route": "report",
        "query": None,
        "answer": (
            f"Your {de.DATASETS[selected]['label']} "
            "PDF report request is ready.\n\n"
            "Select **Download Financial PDF** to "
            "generate the report using your "
            "authorized financial records.\n\n"
            "The report will contain the available "
            "financial summary, budget comparison, "
            "breakdowns and supporting charts."
        ),
        "result": {
            "error": None,
            "message": "PDF report action prepared.",
            "reliability_status": "No answer",
        },
        "report_action": action,
        "suggestions": [],
        "recommendations": [],
    })


