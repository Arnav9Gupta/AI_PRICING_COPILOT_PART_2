def detect_explicit_dataset(question):
    value = str(question or "").lower()

    patterns = {
        "sales": (
            r"\b(sales|revenue|sales orders?|"
            r"order value|sales reps?)\b"
        ),
        "procurement": (
            r"\b(procurement|purchasing|"
            r"purchase orders?|supplier spending)\b"
        ),
        "payroll": (
            r"\b(payroll|gross pay|net pay|"
            r"salaries|salary)\b"
        ),
        "transactions": (
            r"\b(transactions?|transaction amount)\b"
        ),
    }

    for dataset, pattern in patterns.items():
        if re.search(pattern, value, re.I):
            return dataset

    return None


def _resolve_followup(question, history):
    normalized = str(
        question or ""
    ).lower().strip(" .!?")

    if normalized not in {
        "yes",
        "yes please",
        "correct",
        "exactly",
        "that's right",
    }:
        return question

    previous = next(
        (
            item["content"]
            for item in reversed(history)
            if item["role"] == "assistant"
        ),
        "",
    ).lower()

    if "sales orders" in previous:
        return "Give me total sales from Sales Orders"

    if "hr payroll" in previous:
        return "Give me total Gross Pay from HR Payroll"

    return question


